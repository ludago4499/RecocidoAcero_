'''
Generate the property tables of the SAE 1006 and SAE 1010 steel grades in bell_furnace/data.

Each table has the same temperature grid as steel.csv (EN 1993-1-2, generic carbon steel) so all grades
cover the same range.

How each column is built
    cp:  taken from steel.csv (Eurocode 3). The specific heat of low carbon steels is set by the iron
         matrix and barely changes between 0.06 and 0.10 % C, so all grades share it.
    k:   Incropera et al., Fundamentals of Heat and Mass Transfer, Table A.1, at 300, 400, 600, 800
         and 1000 K. SAE 1010 uses the AISI 1010 row. SAE 1006 has no row in the table, so it is
         interpolated in carbon content between Armco iron and AISI 1010. Linear extrapolation below
         300 K, constant above 1000 K (outside the annealing range).
    rho: constant, same carbon interpolation as k.

Usage, from the project root:
    python scripts/generate_steel_tables.py
'''

from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'bell_furnace' / 'data'

# Incropera Table A.1, k in W/(m K) at the temperatures in K
T_ANCHOR = np.array([300.0, 400.0, 600.0, 800.0, 1000.0])
K_ARMCO = np.array([72.7, 65.7, 53.1, 42.2, 32.3])
K_AISI_1010 = np.array([63.9, 58.7, 48.8, 39.2, 31.3])
RHO_ARMCO = 7870.0
RHO_AISI_1010 = 7832.0

# Carbon content in wt % used for the interpolation
C_ARMCO = 0.015  # Armco iron, C <= 0.02
C_AISI_1010 = 0.10  # SAE 1010 range 0.08 to 0.13
GRADE_CARBON = {
    'SAE1006': 0.06,  # SAE 1006 range 0 to 0.08, commercial strip is usually near the top
    'SAE1010': C_AISI_1010,
}


def conductivity(*, T: np.ndarray, k_anchor: np.ndarray) -> np.ndarray:
    '''
    Interpolate k on the temperature grid from the anchor points.

    Args:
        T:        temperatures in K
        k_anchor: conductivity at T_ANCHOR in W/(m K)

    Returns:
        Conductivity in W/(m K) with the shape of T.
    '''
    k = np.interp(T, T_ANCHOR, k_anchor)
    slope = (k_anchor[1] - k_anchor[0]) / (T_ANCHOR[1] - T_ANCHOR[0])
    below = T < T_ANCHOR[0]
    k[below] = k_anchor[0] + slope * (T[below] - T_ANCHOR[0])
    return k


def grade_table(*, grade: str, T: np.ndarray, cp: np.ndarray) -> np.ndarray:
    '''
    Build the property table of one grade.

    Args:
        grade: key of GRADE_CARBON
        T:     temperature grid in K
        cp:    specific heat on that grid in J/(kg K)

    Returns:
        Array with columns T in K, rho in kg/m3, cp in J/(kg K), k in W/(m K).

    Raises:
        ValueError if grade is not in GRADE_CARBON.
    '''
    if grade not in GRADE_CARBON:
        raise ValueError(f'grade must be one of {sorted(GRADE_CARBON)}')
    w = (GRADE_CARBON[grade] - C_ARMCO) / (C_AISI_1010 - C_ARMCO)  # 0 is Armco iron, 1 is AISI 1010
    k_anchor = (1.0 - w) * K_ARMCO + w * K_AISI_1010
    rho = (1.0 - w) * RHO_ARMCO + w * RHO_AISI_1010
    k = conductivity(T=T, k_anchor=k_anchor)
    return np.column_stack([T, np.full_like(T, rho), cp, k])


if __name__ == '__main__':
    base = np.loadtxt(DATA / 'steel.csv', delimiter=',')
    T, cp = base[:, 0], base[:, 2]
    for grade in GRADE_CARBON:
        table = grade_table(grade=grade, T=T, cp=cp)
        header = (
            f'{grade}, {GRADE_CARBON[grade]:.3f} % C, generated by scripts/generate_steel_tables.py\n'
            'cp: EN 1993-1-2. k: Incropera Table A.1 (Armco iron / AISI 1010, interpolated in carbon)\n'
            'T [K], rho [kg/m3], cp [J/(kg K)], k [W/(m K)]'
        )
        path = DATA / f'steel_{grade.lower()}.csv'
        np.savetxt(path, table, delimiter=',', fmt=['%.2f', '%.1f', '%.6e', '%.6e'], header=header)
        print(f'{path.name}: rho {table[0, 1]:.0f} kg/m3, k(300 K) {np.interp(300.0, T, table[:, 3]):.1f} W/(m K)')
