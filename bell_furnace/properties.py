'''
Temperature-dependent properties of the protective gas (pure hydrogen) and the steel strip.

All inputs and outputs are NumPy arrays in SI units, with temperatures in K.

Sources:
    hydrogen: data/hydrogen.csv, generated with CoolProp by scripts/generate_hydrogen_table.py
    steel:    one table per grade, see STEEL_GRADES
              generic: data/steel.csv, EN 1993-1-2 (Eurocode 3), section 3.4.1, carbon steel
              SAE1006, SAE1010: data/steel_sae1006.csv and steel_sae1010.csv, generated by
              scripts/generate_steel_tables.py (cp from Eurocode 3, k and rho from Incropera Table A.1)
'''

from pathlib import Path

import numpy as np

# Load data of values 
_DATA = Path(__file__).resolve().parent / 'data'
_H2_TABLE = np.loadtxt(_DATA / 'hydrogen.csv', delimiter=',')

# Steel grades. 'contact' overrides keys of the CONTACT dict (e.g. hardness) for coils of that grade;
# empty means the case values are used. Ternium has not given hardness or roughness per grade.
STEEL_GRADES = {
    'generic': {'file': 'steel.csv', 'contact': {}},
    'SAE1006': {'file': 'steel_sae1006.csv', 'contact': {}},
    'SAE1010': {'file': 'steel_sae1010.csv', 'contact': {}},
}
_STEEL_TABLES = {}  # cache, grade -> table


def _steel_table(grade: str) -> np.ndarray:
    '''
    Load the property table of a steel grade, once.

    Args:
        grade: key of STEEL_GRADES

    Returns:
        Array with columns T in K, rho in kg/m3, cp in J/(kg K), k in W/(m K).

    Raises:
        ValueError if grade is not in STEEL_GRADES.
    '''
    if grade not in STEEL_GRADES:
        raise ValueError(f'unknown steel grade {grade!r}, use one of {sorted(STEEL_GRADES)}')
    if grade not in _STEEL_TABLES:
        _STEEL_TABLES[grade] = np.loadtxt(_DATA / STEEL_GRADES[grade]['file'], delimiter=',')
    return _STEEL_TABLES[grade]


def steel_density(grade: str = 'generic') -> float:
    '''
    Return the (constant) density of a steel grade.

    Args:
        grade: key of STEEL_GRADES

    Returns:
        Density in kg/m3 at the first table temperature.

    Raises:
        ValueError if grade is not in STEEL_GRADES.
    '''
    return float(_steel_table(grade)[0, 1])


def hydrogen_properties(T_g: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    '''
    Interpolate properties (lineraly) of pure hydrogen from the CoolProp table.

    The table is at 1 atm. Viscosity, conductivity and specific heat are practically independent
    of pressure near atmospheric. We ignore pressure effects on density since it's a small error.

    Args:
        T_g: gas temperature in K

    Returns:
        Tuple (rho, mu, k, cp) of arrays with the shape of T_g: density in kg/m3, dynamic
        viscosity in Pa s, thermal conductivity in W/(m K) and specific heat in J/(kg K).

    Raises:
        ValueError if any temperature is outside the table range.
    '''
    T_g = np.asarray(T_g, dtype=float)
    T_table = _H2_TABLE[:, 0]
    if np.any(T_g < T_table[0]) or np.any(T_g > T_table[-1]):
        raise ValueError(f'temperature must be between {T_table[0]:.0f} and {T_table[-1]:.0f} K')

    rho = np.interp(T_g, T_table, _H2_TABLE[:, 1])
    mu = np.interp(T_g, T_table, _H2_TABLE[:, 2])
    k = np.interp(T_g, T_table, _H2_TABLE[:, 3])
    cp = np.interp(T_g, T_table, _H2_TABLE[:, 4])

    return rho, mu, k, cp


 
def steel_properties(T: np.ndarray, grade: str = 'generic') -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    '''
    Interpolate properties of the steel strip from the table of its grade.
 
    Density is constant in the tables, so thermal expansion is neglected. The thermal
    conductivity is that of solid steel and is used as the axial conductivity.
 
    Args:
        T:     steel temperature in K
        grade: key of STEEL_GRADES ('generic', 'SAE1006', 'SAE1010')
 
    Returns:
        Tuple (rho, cp, k) of arrays with the shape of T: density in kg/m3, specific heat in
        J/(kg K) and thermal conductivity in W/(m K).
 
    Raises:
        ValueError if grade is unknown or any temperature is outside the table range.
    '''
    table = _steel_table(grade)
    T = np.asarray(T, dtype=float)
    T_table = table[:, 0]
    if np.any(T < T_table[0]) or np.any(T > T_table[-1]):
        raise ValueError(f'temperature must be between {T_table[0]:.2f} and {T_table[-1]:.2f} K')
 
    rho = np.interp(T, T_table, table[:, 1])
    cp = np.interp(T, T_table, table[:, 2])
    k = np.interp(T, T_table, table[:, 3])
 
    return rho, cp, k
