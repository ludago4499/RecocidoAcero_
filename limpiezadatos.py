import os
import glob
import warnings
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA
from sklearn.ensemble import RandomForestRegressor

"""Preparacion de entorno, localizamos archivo, cargamos informacion y hacemos primer diagnostico..."""

warnings.filterwarnings('ignore')

ruta = '/content/drive/MyDrive/Colab Notebooks/PCA Recocido/Recocido -Tec.xlsx'

if not os.path.exists(ruta):
    try:
        from google.colab import drive
        drive.mount('/content/drive')
    except Exception:
        pass

if not os.path.exists(ruta):
    encontrados = [f for f in glob.glob('**/*Recocido*.xlsx', recursive=True) if 'Tablas_EDA' not in f]
    if encontrados:
        ruta = encontrados[0]
    else:
        from google.colab import files
        subidos = files.upload()
        ruta = list(subidos.keys())[0]

xls = pd.ExcelFile(ruta, engine='openpyxl')
df = pd.read_excel(xls, sheet_name=xls.sheet_names[0], header=1)
df.columns = [str(c).strip() for c in df.columns]

print(f"Filas totales: {len(df)} | Rollos únicos: {df['Material'].nunique()} | Cargas únicas: {df['RH- Carga'].nunique()}")

"""Analisis de Datos mas profundo: Vemos caracteristicas de los rollos, agrupamos por carga y filtramos."""

rollos = df.drop_duplicates(subset=['Material']).copy()
# Calculamos densidad "aparente"
# Calculamos una densidad a partir de la informacion dada
rho_ap = rollos['RH- Peso Entrada'] / (
    (rollos['RH- Ancho'] / 1000.0) *
    (rollos['RH- Espesor'] / 1000.0) *
    rollos['RH- Largo']
)
# Criterio de densidad
rollos['geom_ok'] = rho_ap.between(7000, 8500)
#Agrupamos rollos que perteenecen a misma carga
agg_rollos = rollos.groupby('RH- Carga').agg(
    num_rollos=('Material', 'count'),
    espesor_max=('RH- Espesor', 'max'),
    espesor_mean=('RH- Espesor', 'mean'),
    ancho_max=('RH- Ancho', 'max'),
    peso_salida_total=('RH- Peso de Salida', 'sum'),
    familia_dom=('RH-Familia acero', lambda s: s.mode().iloc[0]),
    todas_geom_ok=('geom_ok', 'all')
).reset_index()
# RESUMEN de pruebas por carga, mediciones - LABORATORIO
lab_carga = df.groupby('RH- Carga').agg(
    elongacion_lab=('Tensión L - Elongación', 'mean'),
    cedencia_lab=('Tensión L - Punto de cedencia', 'mean'),
    resistencia_lab=('Tensión L - Resistencia', 'mean'),
    elongacion_temple=('Elongación Temple', 'mean')
).reset_index()
#Unificacion de DATOS
# ya tenemos caracteristics fisicas resumidas por carga y resultados de lab resumidos por carga

#Creamos columnas
cols_carga = [
    'RH- Carga', 'RH- Horno', 'RH- Base', 'RH- Enfriador',
    'RH- Peso Carga', 'RH- Temperatura Saturacion', 'RH- Tiempo Saturacion',
    'RH-Tiempo Neto carga', 'RH-Tiempo STD Carga', 'RH-Eficiencia'
]
#Cosntruccion de tabla
cargas = (
    df[cols_carga].drop_duplicates(subset=['RH- Carga'])
    .merge(agg_rollos, on='RH- Carga')
    .merge(lab_carga, on='RH- Carga', how='left')
)

"""Filtrado de Datos......"""

cargas_clean = cargas[
    (cargas['RH- Temperatura Saturacion'] >= 1000) &
    (cargas['RH- Tiempo Saturacion'] > 0) &
    (cargas['RH-Tiempo Neto carga'] < 4500) &
    (cargas['todas_geom_ok'])
].copy()

cargas_clean['Temp_Sat_C'] = (cargas_clean['RH- Temperatura Saturacion'] - 32.0) * (5.0 / 9.0)  ## CONVERSION A CELSIUS
cargas_clean['Tiempo_Neto_h'] = cargas_clean['RH-Tiempo Neto carga'] / 60.0  # conversion a horas
cargas_clean['Tiempo_Sat_h'] = cargas_clean['RH- Tiempo Saturacion'] / 60.0  # conversion a horas
cargas_clean['Peso_Carga_t'] = cargas_clean['RH- Peso Carga'] / 1000.0  # conversion a toneladas

print(f"Cargas válidas tras limpieza de outliers: {len(cargas_clean)} de {len(cargas)}")

cols_corr = [
    'Peso_Carga_t', 'num_rollos', 'espesor_mean', 'ancho_max',
    'Temp_Sat_C', 'Tiempo_Sat_h', 'elongacion_lab', 'cedencia_lab',
    'resistencia_lab', 'Tiempo_Neto_h'
]

# Matriz de correlacion
plt.figure(figsize=(9, 7))
sns.heatmap(cargas_clean[cols_corr].corr(), annot=True, fmt=".2f", cmap="coolwarm", center=0)
plt.title("Sección 1: Matriz de Correlación a Nivel Carga (n=520)")
plt.tight_layout()
plt.show()

"""Parte 2: Exploramos como se relacionan las variables de las cargas y reducir la dimensionalidad de los datos. Ademas, vemos que caracteristicas tienen mayor importancia predictiva

PCA
"""

features_num = ['Peso_Carga_t', 'num_rollos', 'espesor_max', 'espesor_mean', 'ancho_max', 'Temp_Sat_C', 'Tiempo_Sat_h']
# ESTANDARIZAMOS variables
X_scaled = StandardScaler().fit_transform(cargas_clean[features_num])
#ANALISIS COMPONENTES PRINCIPALES - PCA
pca = PCA(n_components=3)
X_pca = pca.fit_transform(X_scaled)

df_pca = pd.DataFrame(X_pca, columns=['PC1', 'PC2', 'PC3'])
df_pca['Tiempo_Neto_h'] = cargas_clean['Tiempo_Neto_h'].reset_index(drop=True)
# buscamos direcciones que capturen la mayor variabilidad posible de los datos
# QUE pROPORCION DE LA VARIANZA TOTAL EXPLICA CADA COMPONENTE
print("\nVarianza explicada por PC1, PC2, PC3 (%):", np.round(pca.explained_variance_ratio_ * 100, 2))
print("Varianza acumulada 3 componentes (%):", round(np.sum(pca.explained_variance_ratio_) * 100, 2))
print("\nCargas factoriales (Loadings):")
print(pd.DataFrame(pca.components_.T, index=features_num, columns=['PC1', 'PC2', 'PC3']).round(3))

#Esto nos permite evaluar qué tanto de la información estadística original estamos conservando al reducir de siete variables a tres componentes.

plt.figure(figsize=(8, 5))
sns.scatterplot(data=df_pca, x='PC1', y='PC2', hue='Tiempo_Neto_h', palette='viridis', s=65)
plt.title("Sección 2:  PCA (PC1 vs PC2) coloreada por Tiempo Neto (h)")
plt.xlabel(f"PC1 ({pca.explained_variance_ratio_[0]*100:.1f}% varianza - Geometría y Masa)")
plt.ylabel(f"PC2 ({pca.explained_variance_ratio_[1]*100:.1f}% varianza - Régimen Térmico)")
plt.tight_layout()
plt.show()

# explicar la variabilidad de las siete variables originales

"""Random Forest para los pesos/importancia de cada variable: que variables ayudan a predecir el tiempo neto de recocido.
Fucnion de objetivo es tiempo neto de recocido = relacion (caracteristicas de la cagra)
t=f(X)
"""

"""Agregamos tres variables categóricas:
- Familia dominante del acero.
- Horno.
- Enfriador.
Porque queremos investigar si las diferencias entre familias de acero y equipos estan relacionadas con el tiempo neto de recocido."""

X_imp = pd.get_dummies(
    cargas_clean[
        features_num + [
            'familia_dom',
            'RH- Horno',
            'RH- Enfriador'
        ]
    ],
    columns=[
        'familia_dom',
        'RH- Horno',
        'RH- Enfriador'
    ],
    drop_first=True
)
#Entrenamiento Random Forest
"Creamos random forest de regresion- Porque queremos predecir una variable numerica continua, el tiempo neto de recocido en horas."
rf_imp = RandomForestRegressor(n_estimators=250, max_depth=8, random_state=42)
rf_imp.fit(X_imp, cargas_clean['Tiempo_Neto_h'])

importancias = pd.Series(rf_imp.feature_importances_, index=X_imp.columns)
resumen_pesos = {
    'Peso de Carga (Peso_Carga_t)': importancias['Peso_Carga_t'],
    'Equipo (Horno y Enfriador)': importancias[[c for c in importancias.index if 'Horno' in c or 'Enfriador' in c]].sum(),
    'Temperatura Saturación (Temp_Sat_C)': importancias['Temp_Sat_C'],
    'Tiempo Saturación (Tiempo_Sat_h)': importancias['Tiempo_Sat_h'],
    'Espesor Rollo (espesor_mean + max)': importancias['espesor_mean'] + importancias['espesor_max'],
    'Ancho Máximo (ancho_max)': importancias['ancho_max'],
    'Número de Rollos (num_rollos)': importancias['num_rollos'],
    'Familia de Acero (familia_dom)': importancias[[c for c in importancias.index if 'familia_dom' in c]].sum()
}
print("\nPeso de cada factor sobre el Tiempo Neto de Recocido (%):")
for factor, peso in pd.Series(resumen_pesos).sort_values(ascending=False).items():
    print(f"  {factor:38s}: {peso*100:5.2f}%")